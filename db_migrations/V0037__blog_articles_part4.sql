На демонстрации система отвечала блестяще, потому что для неё подготовили аккуратные примеры. В реальной работе клиенты пишут с ошибками, присылают фото вместо текста, задают по три вопроса в одном сообщении.

**Как правильно:** тестировать на реальных данных за последние месяцы — со всеми опечатками и странностями. Если система справляется с реальной выборкой, она справится и в работе.


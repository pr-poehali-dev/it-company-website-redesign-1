## Почему «одна большая система» не всегда решение

Первое желание — заменить всё одной системой, которая умеет всё. Иногда это правильно. Но часто такой проект затягивается на год, стоит дорого, и в итоге команда всё равно продолжает пользоваться частью старых инструментов, потому что они удобнее.

Альтернатива — оставить инструменты, которые работают, и связать их между собой.

## Что такое интеграция на практике

Интеграция — это автоматическая передача данных между системами по заданным правилам. Примеры:

- **Заявка с сайта или из мессенджера** → карточка в CRM с источником, ответственным и задачей на звонок.
- **Сделка переведена в «Оплачено»** → счёт в учётной системе и уведомление на склад.
- **Новый клиент** → добавлен в базу рассылки с нужным сегментом.
- **Конец дня** → сводка по продажам руководителю в мессенджер.
- **Изменение остатков** → обновление наличия на сайте.

Где ИИ добавляет пользы: разобрать свободный текст письма, вытащить реквизиты из документа, классифицировать обращение, сделать выжимку длинной переписки перед передачей в CRM.

## Как навести порядок: пошагово

### Шаг 1. Нарисуйте карту

Какие системы есть, кто ими пользуется, какие данные куда переносятся вручную. Обычно на этом этапе обнаруживаются дублирующие сервисы и процессы, которые никто не может объяснить.

### Шаг 2. Определите главную систему

Где «правда» о клиентах и сделках? Обычно это CRM. Все остальные системы должны получать и отправлять данные в неё, а не друг другу напрямую в хаотичном порядке.

### Шаг 3. Начните с самых дорогих переносов

Посчитайте, какие ручные операции занимают больше всего времени или чаще всего приводят к ошибкам. Автоматизируйте их первыми.

### Шаг 4. Уберите лишнее

Если два сервиса делают одно и то же — оставьте один. Каждый лишний инструмент — это ещё одна интеграция и ещё одна подписка.

### Шаг 5. Настройте контроль

Интеграции тоже ломаются: сервис обновил API, истёк токен, изменилось поле. Нужен мониторинг и уведомления о сбоях — иначе вы узнаете о проблеме, когда пропадут заявки.


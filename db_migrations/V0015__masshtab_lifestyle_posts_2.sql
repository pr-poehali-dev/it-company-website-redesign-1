## Почему «буду на связи» не работает

Когда руководитель остаётся доступен, команда продолжает приносить ему вопросы — так проще. В итоге собственник проводит отпуск в переписке, а компания не учится работать без него. Чёткое правило работает лучше: звонить только по заранее оговорённым поводам.

## План подготовки за 6 недель

**Недели 1–2. Список решений.** Записывайте все решения, которые принимаете сами. Разделите их на три группы: можно отменить, можно передать с простым правилом, требуют только вас.

**Недели 3–4. Заместитель.** Назначьте человека, который будет принимать решения в ваше отсутствие. Дайте ему лимит — например, по сумме сделок, скидок, расходов — и доплату за дополнительную ответственность.

**Неделя 5. Пробное отсутствие.** Три рабочих дня не выходите на связь. Потом разберите, какие вопросы возникли и почему.

**Неделя 6. Правила связи.** Договоритесь, по каким поводам вам звонят: авария, угроза потери крупного клиента, проблема с безопасностью. Всё остальное — в еженедельном коротком отчёте.


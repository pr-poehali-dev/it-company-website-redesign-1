## Когда пилот не окупится

- **Прогноз есть, а заказы делают по-старому.** Самая частая причина провала. Если закупщик может «поправить» прогноз без объяснений — эффекта не будет.
- **Нет истории продаж.** Нужно хотя бы 1,5–2 года данных по дням или неделям, с отметками акций и дефицитов.
- **Маленький запас.** Если запас — 20 млн ₽, даже 15 процентов экономии не покроют сопровождение.
- **Нет владельца со стороны бизнеса.** Пилот, который «принадлежит айтишникам», заканчивается красивым отчётом.

## Как запускать пилот правильно

1. Выберите 2–3 категории с большим запасом и частыми дефицитами.
2. До старта зафиксируйте базу: запас, дефицит, списания за последние 3 месяца.
3. Договоритесь о правиле: заказ формируется по прогнозу, отклонения — только с причиной.
4. Через 3 месяца сравните с базой и с контрольными категориями, где ничего не меняли.
5. Масштабируйте, только если эффект виден в деньгах, а не в «точности модели».


## Коротко

- Лицензия — меньшая часть затрат. Подготовка данных, внедрение и сопровождение обычно стоят в 2–3 раза больше.
- Основной эффект прогноза спроса — не «точность модели», а деньги, которые перестают лежать на складе, и продажи, которые перестают теряться из-за пустых полок.

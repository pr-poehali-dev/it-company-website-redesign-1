## Когда облако — плохая идея

Облачные модели удобны: подключил и работаешь. Но есть ситуации, где передавать данные внешнему сервису рискованно или запрещено:

- **Персональные данные клиентов.** Закон о персональных данных накладывает требования к хранению и передаче, особенно за рубеж.
- **Коммерческая тайна.** Условия договоров, финансовая отчётность, ноу-хау производства.
- **Отраслевые требования.** Банки, медицина, госзаказ, оборонные предприятия — свои регламенты по защите информации.
- **Требования крупных заказчиков.** Всё чаще в договорах прямо прописывают запрет передачи данных третьим лицам.
- **Доступность.** Внешний сервис может изменить условия, ограничить доступ из вашего региона или просто не работать в нужный момент.

## Какие есть варианты

### 1. Российские облачные модели

Самый простой шаг: использовать модели отечественных провайдеров с размещением данных в России. Это закрывает вопрос трансграничной передачи, но данные всё равно уходят за пределы компании.

### 2. Модель в частном облаке

Открытая модель разворачивается на арендованных серверах, к которым есть доступ только у вас. Баланс между контролем и затратами: не нужно покупать железо, но данные не уходят к поставщику модели.

### 3. Модель на собственных серверах

Полностью закрытый контур: сервер стоит у вас, интернет для работы модели не нужен. Максимальный контроль, но и максимальные требования к инфраструктуре.

## Насколько локальные модели хуже облачных

Честный ответ: в среднем — уступают самым мощным облачным моделям в сложных рассуждениях. Но для большинства бизнес-задач разница несущественна.

Открытые модели последнего поколения хорошо справляются с:

- выжимками и пересказом документов
- ответами по базе знаний
- классификацией обращений
- извлечением данных из текстов — реквизитов, сумм, дат
- черновиками писем и типовых документов

Хуже — со сложной аналитикой, многоэтапными рассуждениями, нестандартными творческими задачами. Часто разумная схема гибридная: чувствительные данные обрабатываются локально, а обезличенные задачи отправляются в мощную облачную модель.


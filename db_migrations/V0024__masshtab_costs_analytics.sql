## Коротко

- Обещанные 15–20 процентов — это экономия на отдельных статьях затрат, где решения принимаются на данных: запасы, реклама, логистика. Не на всех издержках компании.
- В пересчёте на общие расходы среднего бизнеса реалистичный эффект — 2–5 процентов. Это всё равно десятки миллионов рублей.
- Аналитика экономит деньги, только если меняет конкретное решение: заказ, ставку, маршрут, график.

## Где эффект реален

| Статья затрат | Какое решение меняется | Реалистичная экономия на статье |
|---|---|---|
| Товарные запасы | Сколько и когда заказывать | 10–20 процентов запаса |
| Реклама | Какие каналы и кампании отключить | 15–25 процентов бюджета |
| Логистика | Маршруты, загрузка машин, график поставок | 5–15 процентов |
| Списания и брак | Что и где залёживается | 15–30 процентов списаний |
| Фонд оплаты труда | Графики смен под реальную нагрузку | 3–8 процентов ФОТ линейного персонала |
| Закупки | С какими поставщиками пересмотреть условия | 2–5 процентов закупок |

Самые быстрые деньги обычно в рекламе: отчёт, который связывает расходы на рекламу с реальными оплатами из учётной системы, почти всегда находит кампании, которые тратят бюджет без продаж.

## Сколько это в деньгах: условный пример

Производственно-торговая компания, выручка 1,2 млрд ₽, расходы — 1,1 млрд ₽.

| Статья | Сумма в год | Экономия | В деньгах |
|---|---|---|---|
| Реклама | 36 млн ₽ | 20 процентов | 7,2 млн ₽ |
| Логистика | 60 млн ₽ | 8 процентов | 4,8 млн ₽ |
| Списания | 15 млн ₽ | 20 процентов | 3,0 млн ₽ |
| Деньги в запасах: запас 180 млн ₽, снижение на 12 процентов, стоимость денег 18 процентов годовых | — | — | 3,9 млн ₽ |
| **Итого** | | | **18,9 млн ₽** |

Это 1,7 процента всех расходов компании — и около 20 процентов от затронутых статей. Обе цифры верны, но говорят о разном. Когда вам обещают «15–20 процентов», уточните: от чего именно.

## Где эффекта не будет

- **Постоянные расходы:** аренда, амортизация, управленческий персонал. Аналитика их не снижает — это решения другого уровня.
- **Компании без данных.** Если продажи и расходы ведутся в разных таблицах без единого справочника, первые 2–3 месяца уйдут на наведение порядка.
- **Отчёты, которые никто не читает.** Дашборд без человека, который по нему принимает решения, — расход, а не экономия.

## Как проверить обещание до покупки

1. Попросите назвать 2–3 конкретных решения, которые изменятся, и статьи затрат, на которые они повлияют.
2. Посчитайте базу: сколько сейчас стоят эти статьи за год.
3. Возьмите нижнюю границу обещанной экономии и сравните с полной стоимостью проекта за 3 года, а не с ценой лицензии.
4. Договоритесь о пилоте на одной статье с измеримым результатом через 2–3 месяца.


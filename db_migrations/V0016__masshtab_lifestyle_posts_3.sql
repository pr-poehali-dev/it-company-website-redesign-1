## Почему хобби полезно руководителю

Занятие руками, спорт, музыка, коллекционирование переключают внимание и снижают уровень стресса. Многие руководители замечают, что решения по работе приходят как раз во время такого занятия, а не за столом.

Именно поэтому стоит осторожно относиться к идее «монетизировать» увлечение. Когда хобби становится работой, оно перестаёт быть отдыхом.

## Как проверить идею

**1. Посчитайте честную цену.** Материалы, инструменты, аренда места, ваше время по рыночной ставке мастера. Часто выясняется, что изделие «для души» стоит в три раза дороже, чем готовы платить покупатели.

**2. Продайте первые 5–10 штук.** Не друзьям, а незнакомым людям — через маркетплейс, ярмарку или объявление. Их реакция и готовность платить — главный тест.

**3. Посчитайте, сколько вы можете сделать.** Если на одну вещь уходит неделя вечеров, бизнес не вырастет без помощников. Нужны ли вам сотрудники, обучение, оборудование?

**4. Определите формат.** Продажа изделий, мастер-классы, обучение, аренда мастерской, авторские туры. Иногда выгоднее не делать вещи самому, а учить других.


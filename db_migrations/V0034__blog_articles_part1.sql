## Чем агент отличается от чат-бота

Чат-бот отвечает. Агент — действует.

Классический бот работает по дереву: вопрос — ответ, кнопка — следующий шаг. Языковая модель сделала ответы живыми, но суть та же: бот говорит, а не делает.

Агент получает цель и набор инструментов. Например: «обработай входящую заявку». Инструменты — доступ к CRM, календарю менеджеров, прайсу и почте. Дальше агент сам решает последовательность: прочитать письмо, понять, что клиент хочет, найти его в CRM, проверить наличие, предложить время звонка, создать сделку и написать ответ.

Ключевое слово — **сам решает последовательность**. Именно это и делает агента одновременно полезным и рискованным.

## Где агенты уже работают и окупаются

Хорошая задача для агента — это задача, у которой:

- много повторений (десятки и сотни в день)
- понятный результат, который легко проверить
- ограниченный набор действий
- невысокая цена ошибки или возможность её быстро исправить

Под эти критерии подходят:

- **Разбор входящих заявок.** Прочитать обращение, определить тип, вытащить контакты и суть, завести карточку, назначить ответственного.
- **Первичная квалификация лидов.** Задать 3–5 уточняющих вопросов, отсеять нецелевые обращения, горячие передать человеку.
- **Работа с документами.** Сверить счёт с договором, найти расхождения, подготовить черновик ответа.
- **Внутренняя справочная.** Сотрудник спрашивает «как оформить возврат» — агент находит ответ в регламентах и показывает источник.
- **Мониторинг.** Следить за тендерами, ценами конкурентов, упоминаниями — и присылать только то, что важно.

Во всех этих случаях агент не заменяет отдел. Он снимает с людей рутинную часть, которая занимает много времени и почти не требует экспертизы.


- **Сложные переговоры.** Модель умеет быть вежливой, но не умеет чувствовать момент, когда клиенту нужно уступить.
- **Задачи без формализованного процесса.** Если сами сотрудники каждый раз делают по-разному, агент будет делать по-разному тоже — только быстрее.
- **Длинные цепочки из десятков шагов без контроля.** Каждый шаг — небольшая вероятность ошибки. На длинной дистанции они складываются.

## Главная ошибка внедрения

Самая частая ошибка — начинать с технологии, а не с процесса. «Давайте внедрим агента» — плохая постановка. Хорошая звучит так: «менеджеры тратят 2 часа в день на разбор заявок, давайте сократим это до 20 минут».

Когда есть такая цель, сразу понятно:

- что именно автоматизировать
- как измерить результат
- где поставить человека на контроль

## Как выглядит разумное внедрение

1. **Выбрать один процесс.** Не «автоматизировать продажи», а «разбирать входящие письма с сайта».
2. **Описать, как его делает лучший сотрудник.** Это и будет инструкцией для агента.
3. **Запустить в режиме подсказки.** Агент готовит решение, человек подтверждает одним кликом. Две-три недели собираем статистику: где агент прав, где ошибается.
4. **Перевести в автоматический режим то, где точность стабильно высокая.** Остальное оставить с подтверждением.
5. **Мониторить.** Раз в неделю смотреть выборку решений агента. Процессы меняются — инструкции тоже.


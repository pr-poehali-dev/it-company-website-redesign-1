## Что такое RAG

RAG — это retrieval-augmented generation, «генерация с поиском». Перевод на человеческий: **прежде чем отвечать, нейросеть ищет нужные куски в ваших документах и отвечает только по ним**.

Аналогия — новый сотрудник на испытательном сроке. Он умный, но в компании первую неделю. Когда клиент задаёт вопрос, он не выдумывает, а открывает базу знаний, находит нужный раздел и отвечает по нему. RAG делает то же самое, только за секунду.

## Как это устроено внутри

1. **Подготовка базы.** Документы — регламенты, договоры, инструкции, переписка с ответами — делятся на небольшие фрагменты.
2. **Индексация.** Каждый фрагмент превращается в числовой «отпечаток смысла». Похожие по смыслу тексты получают похожие отпечатки, даже если слова разные.
3. **Поиск.** Пользователь задаёт вопрос. Система находит 5–10 фрагментов, которые ближе всего по смыслу.
4. **Ответ.** Нейросеть получает вопрос и найденные фрагменты с инструкцией: «отвечай только на основе этих материалов, если ответа нет — так и скажи».
5. **Ссылка на источник.** В хорошей системе к ответу прикладывается, из какого документа он взят.

Важно: модель не «обучается» на ваших данных в классическом смысле. Документы не зашиваются внутрь нейросети — их можно обновлять хоть каждый день, и ответы сразу станут актуальными.

## Где RAG приносит пользу

- **Поддержка клиентов.** Ответы на типовые вопросы по условиям, доставке, гарантии — с опорой на актуальные правила.
- **Внутренняя справочная.** «Как оформить командировку», «какой порядок согласования договора» — вместо того чтобы дёргать коллег.
- **Продажи.** Менеджер быстро находит характеристики, сравнение моделей, кейсы под отрасль клиента.
- **Юристы и бухгалтерия.** Поиск похожих пунктов в сотнях договоров, ответы по внутренней методологии.
- **Онбординг.** Новичок задаёт вопросы базе знаний, а не наставнику по двадцать раз в день.

## Подводные камни

### Мусор на входе — мусор на выходе

Если в базе три версии одного регламента, система может процитировать устаревшую. Половина работы над RAG — это наведение порядка в документах. Это скучно, но без этого ничего не работает.

### Таблицы и сканы

Текстовые документы обрабатываются хорошо. Сканы, таблицы со сложной структурой и схемы требуют отдельной подготовки: распознавания, разметки, иногда ручной проверки.

### Слишком большие и слишком маленькие фрагменты

Разрезали документ на крошечные кусочки — теряется контекст. Оставили большие — в ответ попадает много лишнего. Размер фрагментов подбирается под конкретный тип документов.

### Вопросы, на которые нет ответа

Хорошая система должна уметь сказать «в документах этого нет, обратитесь к менеджеру». Это настраивается и обязательно тестируется отдельно.

### Доступы

Не все сотрудники должны видеть все документы. Если у вас есть конфиденциальные разделы, права доступа нужно учитывать прямо в поиске.

## Как проверить качество


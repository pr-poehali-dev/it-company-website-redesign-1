CREATE TABLE IF NOT EXISTS m500_companies (
  inn VARCHAR(12) PRIMARY KEY,
  rev2021 BIGINT,
  rev2022 BIGINT,
  rev2023 BIGINT,
  rev2024 BIGINT,
  rev2025 BIGINT,
  growth NUMERIC(12,2),
  checked_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS m500_growth_idx ON m500_companies (growth DESC NULLS LAST);

CREATE TABLE IF NOT EXISTS mag_posts (
  id SERIAL PRIMARY KEY,
  slug VARCHAR(200) NOT NULL UNIQUE,
  kind VARCHAR(20) NOT NULL DEFAULT 'interview',
  rubric VARCHAR(60) NOT NULL DEFAULT 'Люди',
  title VARCHAR(300) NOT NULL,
  lead TEXT NOT NULL DEFAULT '',
  hero_name VARCHAR(200) NOT NULL DEFAULT '',
  hero_role VARCHAR(300) NOT NULL DEFAULT '',
  company_inn VARCHAR(12),
  cover_url TEXT,
  content TEXT NOT NULL DEFAULT '',
  author VARCHAR(200) NOT NULL DEFAULT 'Редакция «Масштаба»',
  read_min INT NOT NULL DEFAULT 8,
  published BOOLEAN NOT NULL DEFAULT FALSE,
  published_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS mag_posts_pub_idx ON mag_posts (published, published_at DESC);

CREATE TABLE IF NOT EXISTS mag_ads (
  id SERIAL PRIMARY KEY,
  slot VARCHAR(20) NOT NULL DEFAULT 'side',
  advertiser VARCHAR(200) NOT NULL DEFAULT '',
  title VARCHAR(200) NOT NULL DEFAULT '',
  text TEXT NOT NULL DEFAULT '',
  image_url TEXT,
  link TEXT NOT NULL DEFAULT '',
  cta VARCHAR(60) NOT NULL DEFAULT 'Подробнее',
  active BOOLEAN NOT NULL DEFAULT TRUE,
  clicks INT NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS mag_leads (
  id SERIAL PRIMARY KEY,
  kind VARCHAR(20) NOT NULL DEFAULT 'ad',
  name VARCHAR(200) NOT NULL DEFAULT '',
  company VARCHAR(300) NOT NULL DEFAULT '',
  contact VARCHAR(200) NOT NULL,
  message TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
## Как выбрать

**Пробег и интенсивность.** Если машина работает каждый день — у курьеров, выездных мастеров, торговых представителей, — выгоднее собственный парк в лизинге или покупке. Для двух-трёх поездок в месяц дешевле компенсация или такси.

**Деньги в обороте.** При дорогих кредитах каждый рубль, оставшийся в бизнесе, ценен. Лизинг с авансом 10–20% часто выгоднее покупки, даже с учётом переплаты, если деньги в обороте приносят больше.

**Налоги.** Порядок учёта расходов и НДС зависит от вашей системы налогообложения. На упрощённой системе и на общей выгода от лизинга разная — уточните у бухгалтера до подписания договора.


## Что входит в стоимость владения

Посчитайте каждую статью за весь срок использования, например за четыре года:

- **Деньги за машину:** цена покупки или сумма лизинговых платежей, включая аванс.
- **Страхование:** обязательное и добровольное, если берёте.
- **Обслуживание и ремонт:** плановое ТО, шины, расходники.
- **Топливо:** пробег в год × расход на 100 км × цена литра.

## Что умеет компьютерное зрение

Если упростить, система делает одно из четырёх действий:

- **Находит объекты**: человек, деталь, коробка, автомобиль.
- **Классифицирует**: годная деталь или брак, какой тип продукта.
- **Измеряет**: размеры, количество, положение, заполненность.
- **Отслеживает**: перемещение объекта или человека в кадре во времени.

Всё остальное — комбинации этих действий с бизнес-логикой: «если в опасной зоне человек без каски — отправить уведомление мастеру».

## Где камера с ИИ окупается быстро

### Контроль качества на конвейере

Человек на визуальном контроле устаёт, отвлекается и к концу смены пропускает больше брака. Камера смотрит на каждое изделие одинаково внимательно. Подходит для задач, где дефект виден глазом: сколы, царапины, неправильная маркировка, отсутствие комплектующих.

### Охрана труда

Распознавание касок, жилетов, нахождения в опасной зоне. Цена одного несчастного случая — штрафы, простой и человеческие последствия — часто превышает стоимость всей системы.

### Подсчёт и учёт

Количество продукции на выходе линии, загрузка транспорта, заполненность складских ячеек. Вместо ручного пересчёта — данные в реальном времени.

### Контроль процессов

Соблюдение технологической последовательности операций, время цикла, простои оборудования — всё, что раньше фиксировалось вручную или не фиксировалось вовсе.

## Где проекты проваливаются

### Нет данных о дефектах

Чтобы научить систему находить брак, нужны примеры брака. Если дефекты редкие, а фото никто не собирал, первые месяцы уйдут на сбор данных. Об этом нужно знать заранее.

### Нестабильные условия съёмки

Блики, пыль, вибрация, меняющееся освещение, разный фон. Модель, отлично работавшая на тестовых фото, может ошибаться в реальном цехе. Половина успеха — правильная установка камеры и освещения.

### Задача, которую глаз не видит

Если дефект внутри изделия или различим только под микроскопом, обычная камера не поможет. Нужны другие методы контроля.

### Нет реакции на сигнал

Система нашла брак — а дальше что? Если некому остановить линию или отбраковать изделие, все уведомления останутся в журнале. Внедрение должно включать изменение процесса, а не только установку камеры.

### Ожидание стопроцентной точности

Любая система иногда ошибается. Важно заранее договориться, что хуже — пропустить брак или забраковать годное изделие, и настроить модель под этот баланс.

## Как считать окупаемость

Простая формула для контроля качества:

- сколько стоит один пропущенный дефект (возвраты, рекламации, переделка, репутация)
- сколько дефектов в месяц сейчас пропускается
- сколько часов уходит на ручной контроль
- стоимость системы и её обслуживания

Если экономия на браке и ручном контроле за год заметно превышает стоимость внедрения — проект имеет смысл. Если нет — стоит поискать задачу с большим эффектом.


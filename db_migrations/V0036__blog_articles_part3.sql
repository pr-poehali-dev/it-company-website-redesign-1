## Как сделать, чтобы клиент не бросил трубку

### Честность

Ассистент должен сразу сообщать, что он виртуальный помощник. Попытка выдать робота за человека разрушает доверие, как только клиент это заметит. А он заметит.

### Быстрый выход на человека

Фраза «соедините с оператором» должна работать с первого раза. Ассистент, который не отпускает клиента, — худший сценарий.

### Короткие реплики

В письменном чате длинный ответ терпим, по телефону — нет. Ответы должны быть короткими и заканчиваться понятным вопросом или действием.

### Скорость реакции

Пауза в несколько секунд по телефону воспринимается как сбой. Задержка ответа — критически важный параметр при выборе технологий.

### Настройка под ваш бизнес

Названия услуг, адреса, имена врачей или мастеров, местные особенности произношения — всё это нужно отдельно протестировать на распознавание.


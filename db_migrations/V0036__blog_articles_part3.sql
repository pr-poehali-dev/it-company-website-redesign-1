- **Сопровождение** — от 30 тысяч рублей в месяц.

Точная стоимость зависит от числа интеграций, качества данных и требований к безопасности.

## Где можно сэкономить

- **Начать с пилота.** Проверить эффект на одном процессе, прежде чем автоматизировать всё.
- **Использовать готовые модели.** Обучение собственной модели с нуля нужно в редких случаях.
- **Выбирать модель под задачу.** Для классификации заявок не нужна самая дорогая модель — небольшая справится не хуже и обойдётся в разы дешевле.
- **Использовать готовые коннекторы** к популярным CRM и сервисам вместо разработки с нуля.

## На чём экономить опасно

- **На анализе процесса.** Автоматизировать хаос — получить быстрый хаос.
- **На тестировании.** Ошибка ИИ в общении с клиентом стоит дороже, чем неделя тестов.
- **На безопасности.** Утечка клиентских данных обойдётся несопоставимо дороже защиты.
- **На сопровождении.** Система без поддержки деградирует за несколько месяцев.

## Как посчитать окупаемость

1. Сколько часов в месяц сотрудники тратят на задачу.
2. Стоимость часа с учётом налогов и накладных расходов.
3. Сколько продаж теряется из-за медленной реакции или ошибок.
4. Сравнить с затратами на внедрение и ежемесячным содержанием.

Если проект не окупается за разумный срок на бумаге — лучше выбрать другой процесс или отложить.


## Из чего состоит бюджет

### 1. Анализ и проектирование

Прежде чем что-то делать, нужно понять процесс: кто что делает, где теряется время, какие данные есть, какие системы задействованы. На этом этапе часто выясняется, что половину проблемы можно решить без ИИ — простой автоматизацией или изменением регламента.

Доля в бюджете небольшая, но это этап, который сильнее всего влияет на результат.

### 2. Подготовка данных

Документы, переписка, справочники, история заявок. Их нужно собрать, очистить от дублей и устаревшего, привести к единому виду. Для проектов с базой знаний это может быть самой трудоёмкой частью.

### 3. Интеграции

ИИ должен получать данные из ваших систем и записывать результат обратно: CRM, учётная система, почта, мессенджеры, телефония, сайт. Каждая интеграция — это отдельная работа, особенно если система старая или самописная.

Чаще всего именно интеграции составляют наибольшую часть стоимости проекта.

### 4. Настройка сценариев и инструкций

Как ИИ должен отвечать, что можно и что нельзя, когда звать человека, в каком формате выдавать результат. Это итеративная работа: настроили — проверили на реальных примерах — поправили.

### 5. Тестирование

Набор реальных кейсов, прогон, анализ ошибок, доработка. Без этого этапа вы узнаете о проблемах от клиентов.

### 6. Оплата модели

Облачные модели берут деньги за объём обработанного текста. Для типовых задач — ответы клиентам, разбор заявок — расходы обычно измеряются тысячами или десятками тысяч рублей в месяц даже при большом потоке. Локальная модель на своих серверах требует вложений в железо, но не имеет платы за запросы.

### 7. Сопровождение

Процессы меняются, появляются новые товары и правила, модели обновляются. Систему нужно мониторить и дорабатывать. Ежемесячные расходы на сопровождение — нормальная часть бюджета, а не признак того, что «что-то сделали плохо».


def call_ai(prompt, timeout):
    key = os.environ.get('POLZA_AI_API_KEY', '')
    body = json.dumps({'model': MODEL, 'messages': [{'role': 'user', 'content': prompt}], 'temperature': 0.7, 'max_tokens': 4000,
                       'response_format': {'type': 'json_object'}}).encode()
    req = urllib.request.Request(AI_URL, data=body, method='POST', headers={'Content-Type': 'application/json', 'Authorization': f'Bearer {key}'})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        data = json.loads(r.read().decode())
    return data['choices'][0]['message']['content']


def parse(raw):
    raw = raw.strip()
    m = re.search(r'\{.*\}', raw, re.S)
    return json.loads(m.group(0) if m else raw)


def generate_case(track, topic, used, deadline):
    t = BY_SLUG.get(track) or TRACKS[0]
    if not topic:
        low = ' '.join(used).lower()
        pool = [x for x in t['topics'] if not any(w in low for w in x.lower().split()[:2])] or t['topics']
        topic = pool[int(time.time() // 86400) % len(pool)]
    timeout = max(10, min(85, deadline - time.time() - 2))
    raw = call_ai(PROMPT.format(topic=topic, track=t['name'], used='; '.join(used[:40]) or 'нет'), timeout)
    d = parse(raw)
    content = (d.get('content') or '').strip()
    title = re.sub(r'\s+', ' ', (d.get('title') or '').strip().strip('«»"'))
    if len(content) < 2500 or not title:
        raise ValueError('ИИ вернул слишком короткий текст')
    if 'вымышлен' not in content:
        content += '\n\n*Кейс составлен редакцией на основе типичных ситуаций малого и среднего бизнеса; компания и герои вымышлены, совпадения случайны.*'
    tk = d.get('takeaways') or []
    tk = tk if isinstance(tk, list) else [str(tk)]
    words = len(re.findall(r'\S+', content))
    return {
        'track': t['slug'], 'title': title[:300], 'lead': (d.get('lead') or '').strip()[:1000], 'content': content,
        'takeaways': '\n'.join(str(x).strip() for x in tk if str(x).strip())[:4000], 'question': (d.get('question') or '').strip()[:4000],
        'sources': '', 'read_min': max(3, round(words / 180)),
    }

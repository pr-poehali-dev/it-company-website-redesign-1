"""Модуль «Мой план на 5 лет»: личная стратегия роста по методике «Профориентации PRO» учисьпро.рф.
План составляет ИИ по анкете; если ИИ недоступен или не хватает времени — собирается по шаблону из тех же ответов."""
import json
import os
import re
import time

import requests

AI_URL = 'https://api.polza.ai/v1/chat/completions'
MODEL = 'gpt-4o-mini'
FIELDS = {'goal': 300, 'direction': 120, 'situation': 200, 'strengths': 300, 'obstacle': 200, 'income_now': 60, 'income_goal': 60}
STAGES = ['Фундамент', 'Первые результаты', 'Экспертность', 'Рост и масштаб', 'Устойчивость']


def clean(m):
    out = {k: re.sub(r'\s+', ' ', str(m.get(k) or '')).strip()[:n] for k, n in FIELDS.items()}
    try:
        out['age'] = max(14, min(80, int(m.get('age')))) if m.get('age') not in (None, '') else ''
    except (TypeError, ValueError):
        out['age'] = ''
    try:
        out['hours'] = max(1, min(60, int(m.get('hours') or 8)))
    except (TypeError, ValueError):
        out['hours'] = 8
    return out


PROMPT = """Ты — наставник-стратег образовательной платформы УЧИСЬПРО. Составь личный план успеха на 5 лет для человека.
Методика: длинный горизонт, разбитый по годам. У каждого года — название этапа, главный фокус, 3–4 контрольные точки
с измеримым результатом и одна ключевая метрика (число, а не лозунг). Реалистично для указанного времени в неделю.
Пиши на «вы», по-русски, конкретно, без воды и без обещаний гарантированного дохода.

Анкета:
- Цель через 5 лет: {goal}
- Направление: {direction}
- Возраст: {age}
- Ситуация сейчас: {situation}
- Сильные стороны: {strengths}
- Время на развитие: {hours} ч в неделю
- Доход сейчас: {income_now}; цель по доходу: {income_goal}
- Что чаще всего мешает: {obstacle}

Ответ — строго JSON:
{{"summary": "2–3 предложения: куда ведёт план и почему он опирается на сильные стороны",
 "years": [{{"stage": "название этапа", "focus": "главный фокус года, 1 предложение",
            "checkpoints": ["3–4 контрольные точки с измеримым результатом"], "metric": "одна ключевая метрика года"}}],
 "first_week": ["3 конкретных шага на первую неделю"],
 "risks": [{{"risk": "что может остановить", "answer": "что делать"}}]}}
Ровно 5 элементов в years, 3 элемента в first_week, 3 элемента в risks."""


def ai_plan(f, timeout):
    key = os.environ.get('POLZA_AI_API_KEY')
    if not key or timeout < 6:
        print(f'[custom] plan5: шаблон вместо ИИ (ключ: {bool(key)}, времени: {timeout:.0f} с)')
        return None
    vals = {k: (f.get(k) or 'не указано') for k in list(FIELDS) + ['age', 'hours']}
    r = requests.post(AI_URL, timeout=timeout, headers={'Authorization': f'Bearer {key}'},
                      json={'model': MODEL, 'temperature': 0.6, 'max_tokens': 2200, 'response_format': {'type': 'json_object'},
                            'messages': [{'role': 'user', 'content': PROMPT.format(**vals)}]})
    r.raise_for_status()
    raw = r.json()['choices'][0]['message']['content']
    m = re.search(r'\{.*\}', raw, re.S)
    d = json.loads(m.group(0) if m else raw)
    years = [y for y in d.get('years') or [] if isinstance(y, dict) and y.get('checkpoints')][:5]
    if len(years) < 5:
        return None
    return {'summary': str(d.get('summary') or ''), 'years': years, 'first_week': [str(x) for x in (d.get('first_week') or [])][:3],
            'risks': [x for x in (d.get('risks') or []) if isinstance(x, dict)][:3], 'ai': True}


def template_plan(f):
    goal = f['goal'] or 'выйти на новый уровень в выбранном деле'
    d = f['direction'] or 'выбранном направлении'
    h = f['hours']
    inc = f['income_goal']
    metrics = [f'не меньше {h * 40} часов практики за год и 1 завершённый курс', '3 реальных проекта или клиента',
               '10 проектов в портфолио и первые рекомендации', 'доход ' + (inc if inc else 'на 50% выше стартового'), 'стабильный результат 12 месяцев подряд']
    focus = [f'Освоить основы направления «{d}» и выстроить ритм занятий {h} ч в неделю.',
             'Применить знания на практике и получить первые деньги или первые достижения.',
             'Стать заметным специалистом: портфолио, отзывы, понятное предложение.',
             'Увеличить масштаб: цены, команда, партнёры или новая должность.',
             f'Закрепить результат и подойти к цели: {goal}.']
    cps = [['Выбрать один обучающий курс и пройти его до конца', 'Сделать первую учебную работу и показать её наставнику', 'Найти 2–3 человек из профессии и поговорить с ними', 'Закрепить расписание: занятия в одни и те же дни'],
           ['Сделать первый проект для реального заказчика или работодателя', 'Собрать отзыв и разбор ошибок по каждому проекту', 'Посчитать, сколько часов уходит на один результат'],
           ['Оформить портфолио из лучших работ', 'Выступить или опубликовать разбор своего кейса', 'Поднять цену или перейти на следующий уровень должности'],
           ['Делегировать или автоматизировать рутину', 'Выйти на новых клиентов или новый рынок', 'Создать «подушку» на 3–6 месяцев расходов'],
           ['Сверить итог с целью и записать, что получилось', 'Передать опыт: наставничество, курс или статья', 'Поставить цели на следующие 5 лет']]
    return {'summary': f'План ведёт к цели «{goal}» через пять этапов. Темп рассчитан на {h} ч в неделю: это немного, '
                       'но если не пропускать — за пять лет набирается больше тысячи часов практики.',
            'years': [{'stage': STAGES[i], 'focus': focus[i], 'checkpoints': cps[i], 'metric': metrics[i]} for i in range(5)],
            'first_week': ['Записать цель одним предложением и повесить на видное место', f'Выбрать два дня и время для занятий — всего {h} ч',
                           'Сделать первый маленький шаг: найти курс, книгу или человека из профессии'],
            'risks': [{'risk': 'Пропал запал через 2–3 недели', 'answer': 'Уменьшить шаг до 15 минут в день, но не пропускать ни одного дня.'},
                      {'risk': f'Мешает: {f["obstacle"]}' if f['obstacle'] else 'Не хватает времени', 'answer': 'Найти одну задачу, которую можно убрать или передать, и освободить это время.'},
                      {'risk': 'Кажется, что прогресса нет', 'answer': 'Раз в месяц сверяться с метрикой года — цифры показывают движение лучше, чем ощущения.'}],
            'ai': False}


def make(f, deadline):
    try:
        p = ai_plan(f, min(45, deadline - time.time() - 5))
        if p:
            return p
    except Exception as e:
        print(f'[custom] plan5 ai: {e}')
    return template_plan(f)

# Порядок отображения сегментов
SEGMENT_ORDER = ['education', 'manufacturing', 'food', 'retail', 'digital']


def match_segment(prospect: dict) -> str:
    """Определяет сегмент компании по названию/отрасли/описанию. '' если не определён."""
    text = ' '.join([
        str(prospect.get('company_name') or ''),
        str(prospect.get('industry') or ''),
        str(prospect.get('description') or ''),
    ]).lower()
    for key in SEGMENT_ORDER:
        for kw in SEGMENTS[key]['keywords']:
            if kw in text:
                return key
    return ''


